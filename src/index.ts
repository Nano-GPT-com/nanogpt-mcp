#!/usr/bin/env node
/**
 * NanoGPT MCP Server
 *
 * An MCP server that provides access to NanoGPT's API capabilities:
 * - Chat completion
 * - Image generation
 * - Web search
 * - URL scraping
 * - Application scrapers
 * - X Research and Hunter data tools
 * - Embeddings, audio/music, video, image editing, AI QR, and AI detection
 * - YouTube transcription
 * - Model listing
 *
 * Uses stdio transport for communication with MCP clients.
 *
 * Pinned MCP SDK version: @modelcontextprotocol/sdk@^1.25.2
 */

import { McpServer, ResourceTemplate } from '@modelcontextprotocol/sdk/server/mcp.js';
import { StdioServerTransport } from '@modelcontextprotocol/sdk/server/stdio.js';
import { loadConfig, log } from './config.js';
import { read, clearCache } from './resources.js';
import { abortAllRequests, getActiveRequestCount } from './activeRequests.js';
import {
  balance,
  chat,
  imageGenerate,
  vision,
  webSearch,
  scrapeUrls,
  firecrawl,
  googleMaps,
  googleMapsReviews,
  reddit,
  facebookAds,
  facebookPosts,
  instagramProfile,
  instagramPosts,
  instagramReels,
  linkedinProfile,
  tiktok,
  hunter,
  xResearch,
  aiDetection,
  aiQr,
  audioTranscribe,
  embeddings,
  imageEdit,
  musicGenerate,
  textToSpeech,
  videoGenerate,
  model3dGenerate,
  youtubeTranscribe,
  listTextModels,
  listImageModels,
  listAudioModels,
  listVideoModels,
  list3dModels,
} from './tools/index.js';

/**
 * Main entry point
 */
async function main() {
  // Load and validate configuration
  const config = loadConfig();
  log('info', 'NanoGPT MCP server starting', { baseUrl: config.baseUrl });

  // Create MCP server
  const server = new McpServer({
    name: 'nanogpt-mcp',
    version: '1.5.1',
  });

  // Register tools
  registerTools(server);

  // Register resource handlers
  registerResources(server);

  // Setup graceful shutdown
  setupShutdown();

  // Connect via stdio transport
  const transport = new StdioServerTransport();
  await server.connect(transport);

  log('info', 'NanoGPT MCP server connected and ready');
}

/**
 * Register all tools with the MCP server
 */
function registerTools(server: McpServer) {
  const tools = [
    balance,
    chat,
    imageGenerate,
    vision,
    webSearch,
    scrapeUrls,
    firecrawl,
    googleMaps,
    googleMapsReviews,
    reddit,
    facebookAds,
    facebookPosts,
    instagramProfile,
    instagramPosts,
    instagramReels,
    linkedinProfile,
    tiktok,
    hunter,
    xResearch,
    aiDetection,
    aiQr,
    audioTranscribe,
    embeddings,
    imageEdit,
    musicGenerate,
    textToSpeech,
    videoGenerate,
    model3dGenerate,
    youtubeTranscribe,
    listTextModels,
    listImageModels,
    listAudioModels,
    listVideoModels,
    list3dModels,
  ];

  for (const tool of tools) {
    const outputSchema = 'outputSchema' in tool ? tool.outputSchema : undefined;
    server.registerTool(
      tool.name,
      {
        description: tool.description,
        // MCP SDK v1.23+ accepts Zod schemas and converts to JSON Schema internally
        inputSchema: tool.inputSchema,
        ...(outputSchema ? { outputSchema } : {}),
        annotations: tool.annotations,
      },
      tool.handler as Parameters<typeof server.registerTool>[2]
    );
  }

  log('info', `Registered ${tools.length} tools`);
}

/**
 * Register resource handlers for reading stored resources
 */
function registerResources(server: McpServer) {
  type Variables = Record<string, string | string[]>;

  // Resource template for raw JSON responses
  const rawTemplate = new ResourceTemplate('nanogpt://raw/{id}', { list: undefined });
  server.registerResource(
    'nanogpt-raw',
    rawTemplate,
    {
      description: 'Raw JSON response from NanoGPT API',
      mimeType: 'application/json',
    },
async (uri: URL, _variables: Variables) => {
      const uriString = uri.toString();
      const result = read(uriString);

      if (!result || !result.text) {
        return {
          contents: [
            {
              uri: uriString,
              mimeType: 'text/plain',
              text: `Resource not found (may have been evicted): ${uriString}`,
            },
          ],
        };
      }

      return {
        contents: [
          {
            uri: uriString,
            mimeType: result.mimeType,
            text: result.text,
          },
        ],
      };
    }
  );

  // Resource template for stored images
  const imageTemplate = new ResourceTemplate('nanogpt://image/{id}', { list: undefined });
  server.registerResource(
    'nanogpt-image',
    imageTemplate,
    {
      description: 'Image generated by NanoGPT',
      mimeType: 'image/*',
    },
async (uri: URL, _variables: Variables) => {
      const uriString = uri.toString();
      const result = read(uriString);

      if (!result || !result.blob) {
        return {
          contents: [
            {
              uri: uriString,
              mimeType: 'text/plain',
              text: `Resource not found (may have been evicted): ${uriString}`,
            },
          ],
        };
      }

      return {
        contents: [
          {
            uri: uriString,
            mimeType: result.mimeType,
            blob: result.blob,
          },
        ],
      };
    }
  );

  // Resource template for generated media (audio/video)
  const mediaTemplate = new ResourceTemplate('nanogpt://media/{id}', { list: undefined });
  server.registerResource(
    'nanogpt-media',
    mediaTemplate,
    {
      description: 'Media generated by NanoGPT',
      mimeType: 'application/octet-stream',
    },
    async (uri: URL, _variables: Variables) => {
      const uriString = uri.toString();
      const result = read(uriString);

      if (!result || !result.blob) {
        return {
          contents: [
            {
              uri: uriString,
              mimeType: 'text/plain',
              text: `Resource not found (may have been evicted): ${uriString}`,
            },
          ],
        };
      }

      return {
        contents: [
          {
            uri: uriString,
            mimeType: result.mimeType,
            blob: result.blob,
          },
        ],
      };
    }
  );

  log('info', 'Registered resource handlers for nanogpt://raw/*, nanogpt://image/*, and nanogpt://media/*');
}

/**
 * Setup graceful shutdown handlers
 */
function setupShutdown() {
  const shutdown = async (signal: string) => {
    const activeCount = getActiveRequestCount();
    log('info', `Received ${signal}, shutting down...`, { activeRequests: activeCount });

    // Abort all active HTTP requests
    abortAllRequests();

    // Clear resource cache
    clearCache();

    log('info', 'Shutdown complete');
    process.exit(0);
  };

  process.on('SIGINT', () => shutdown('SIGINT'));
  process.on('SIGTERM', () => shutdown('SIGTERM'));

  // Handle uncaught errors
  process.on('uncaughtException', (err) => {
    log('error', 'Uncaught exception', { error: err.message });
    process.exit(1);
  });

  process.on('unhandledRejection', (reason) => {
    log('error', 'Unhandled rejection', {
      error: reason instanceof Error ? reason.message : String(reason),
    });
    process.exit(1);
  });
}

// Run the server
main().catch((err) => {
  console.error('Fatal error:', err);
  process.exit(1);
});
